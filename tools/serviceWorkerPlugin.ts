import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import type { Plugin, ResolvedConfig } from 'vite';

/**
 * Files that are not worth downloading up front. They are still cached the
 * first time the browser actually asks for them.
 *  - og-image: only read by link-preview crawlers
 *  - font subsets other than latin/latin-ext: the UI is Swedish/English
 *  - source maps and the worker itself
 */
const SKIP_PRECACHE = [
  /(^|\/)sw\.js$/,
  /\.map$/,
  /(^|\/)og-image\./,
  /-(cyrillic|cyrillic-ext|greek|greek-ext|vietnamese)-[^/]*\.woff2$/,
];

function listFiles(dir: string, root = dir): string[] {
  const out: string[] = [];
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) out.push(...listFiles(full, root));
    else out.push(relative(root, full).split('\\').join('/'));
  }
  return out.sort();
}

export function buildServiceWorkerSource(files: string[], version: string): string {
  return `// Generated by tools/serviceWorkerPlugin.ts — do not edit.
const CACHE = 'animalpuzzle-${version}';
const PRECACHE = ${JSON.stringify(['./', ...files], null, 2)};

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches
      .open(CACHE)
      .then((cache) => cache.addAll(PRECACHE))
      .then(() => self.skipWaiting())
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) =>
        Promise.all(
          keys
            .filter((key) => key.startsWith('animalpuzzle-') && key !== CACHE)
            .map((key) => caches.delete(key))
        )
      )
      .then(() => self.clients.claim())
  );
});

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET') return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;

  // Pages: try the network first so a new release shows up immediately,
  // and fall back to the cached shell when offline.
  if (request.mode === 'navigate') {
    event.respondWith(
      fetch(request)
        .then((response) => {
          if (response.ok) {
            const copy = response.clone();
            caches.open(CACHE).then((cache) => cache.put('./', copy));
          }
          return response;
        })
        .catch(() => caches.match('./', { cacheName: CACHE }))
    );
    return;
  }

  // Everything else is content-hashed or static: cache first.
  event.respondWith(
    caches.match(request, { cacheName: CACHE }).then((cached) => {
      if (cached) return cached;
      return fetch(request).then((response) => {
        if (response.ok && response.type === 'basic') {
          const copy = response.clone();
          caches.open(CACHE).then((cache) => cache.put(request, copy));
        }
        return response;
      });
    })
  );
});
`;
}

/** Writes dist/sw.js after the build, listing every built file for precaching. */
export function serviceWorkerPlugin(): Plugin {
  let config: ResolvedConfig;
  return {
    name: 'animalpuzzle-service-worker',
    apply: 'build',
    configResolved(resolved) {
      config = resolved;
    },
    closeBundle() {
      const outDir = join(config.root, config.build.outDir);
      const files = listFiles(outDir).filter(
        (file) => file !== 'index.html' && !SKIP_PRECACHE.some((pattern) => pattern.test(file))
      );
      // The version changes whenever any precached file changes.
      const hash = createHash('sha256');
      for (const file of ['index.html', ...files]) {
        hash.update(file);
        hash.update(readFileSync(join(outDir, file)));
      }
      const version = hash.digest('hex').slice(0, 12);
      writeFileSync(join(outDir, 'sw.js'), buildServiceWorkerSource(files, version));
      config.logger.info(`service worker: ${files.length + 1} files precached (${version})`);
    },
  };
}
